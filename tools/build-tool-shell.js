#!/usr/bin/env node
/**
 * build-tool-shell.js — generate assets/tool-shell.css from style.css.
 *
 * The 15 self-contained calculator pages (wacc, epv, comps, pe-*, ...) carry
 * their own page CSS and must not load the full site stylesheet: its bare
 * element rules (h1, p, a, ul, img) would restyle the calculators and the
 * golden-output smoke test depends on their layout. What they DO share with
 * the rest of the site is the chrome: skip link, header, nav, mobile menu,
 * footer. This script extracts exactly those rules (plus the :root tokens
 * they reference) from style.css so the chrome is never hand-duplicated.
 *
 * Runs in `npm run manifests`. Output is committed (static site, no build
 * on deploy). Edit style.css, never the generated file.
 */
const fs = require("fs");
const path = require("path");

const SRC = path.join(__dirname, "..", "style.css");
const OUT = path.join(__dirname, "..", "assets", "tool-shell.css");
const css = fs.readFileSync(SRC, "utf8");

// Selectors that belong to the shared chrome. The theme toggle is deliberately
// excluded: the calculators are light-only, so the toggle is not rendered there.
const CHROME = /^(\.skip-link|\.site-header|\.brand\b|\.nav-toggle|\.site-nav|\.nav-subscribe|\.site-footer|\.footer-inner|\.social\b|\.copy\b)/;

function stripComments(s) {
  return s.replace(/\/\*[\s\S]*?\*\//g, "").trim();
}

// Split a stylesheet (or a @media body) into [selector, body] blocks.
function blocks(text) {
  const out = [];
  let i = 0;
  while (i < text.length) {
    const open = text.indexOf("{", i);
    if (open < 0) break;
    const sel = text.slice(i, open);
    let depth = 1, k = open + 1;
    while (k < text.length && depth) {
      if (text[k] === "{") depth++;
      else if (text[k] === "}") depth--;
      k++;
    }
    out.push([sel, text.slice(open + 1, k - 1)]);
    i = k;
  }
  return out;
}

function keep(selectorList) {
  return stripComments(selectorList)
    .split(",")
    .map((s) => s.trim())
    .filter((s) => CHROME.test(s));
}

const kept = [];
let root = null;
for (const [rawSel, body] of blocks(css)) {
  const sel = stripComments(rawSel);
  if (!sel) continue;
  if (sel === ":root" && !root) { root = body.trim(); continue; }
  if (sel.startsWith("@media")) {
    const inner = [];
    for (const [s2, b2] of blocks(body)) {
      const ks = keep(s2);
      if (ks.length) inner.push(`  ${ks.join(", ")} {${b2.replace(/\n/g, "\n  ")}}`);
    }
    if (inner.length) kept.push(`${sel} {\n${inner.join("\n")}\n}`);
    continue;
  }
  const ks = keep(sel);
  if (ks.length) kept.push(`${ks.join(", ")} {${body}}`);
}

if (!root) { console.error("build-tool-shell: no :root block found in style.css"); process.exit(1); }

const out = `/* GENERATED by tools/build-tool-shell.js from style.css — do not edit.
   Shared site chrome (skip link, header, nav, mobile menu, footer) for the
   self-contained calculator pages, which keep their own page CSS. */
:root {${root ? "\n" + root + "\n" : ""}}
html { color-scheme: light; }
${kept.join("\n")}

/* Calculator pages: the shell owns the page edges; the tool body keeps its
   own gutters inside <main class="tool-main">. */
body.tool-page { padding: 0; }
.tool-main { padding: 36px 40px 100px; }
@media (max-width: 900px) { .tool-main { padding: 24px 20px 80px; } }
/* The calculators' fixed "Share this" button and its toast used to sit in the
   top-right corner above the old inline header; the shared header is sticky,
   so they move below it. */
.tool-page .share-btn { top: 112px; }
.tool-page .share-toast { top: 158px; }
`;

const prev = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : null;
if (prev !== out) {
  fs.writeFileSync(OUT, out, "utf8");
  console.log(`build-tool-shell: wrote assets/tool-shell.css (${kept.length} chrome rules)`);
} else {
  console.log(`build-tool-shell: unchanged (${kept.length} chrome rules)`);
}
