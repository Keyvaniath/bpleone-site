#!/usr/bin/env node
// Rebuild assets/reports/manifest.json from the contents of assets/reports/.
// Picks up every *.pdf file. Preserves human-edited fields (title, subtitle,
// type, published, page, notes, gated flag) when re-running by reading the
// existing manifest and matching on file path.
//
// Usage: node tools/build-reports-manifest.js
//
// Convention for grouping multiple files into one report:
//   - Files in the same "report id" share a path prefix up to the first
//     "-full-" / "-preview-" / "-appendix-" segment.
//   - Or you can edit manifest.json by hand and just bump `size` here.

const fs = require('fs');
const path = require('path');

const REPORTS_DIR = path.join(__dirname, '..', 'assets', 'reports');
const MANIFEST = path.join(REPORTS_DIR, 'manifest.json');

function loadExisting() {
  try { return JSON.parse(fs.readFileSync(MANIFEST, 'utf8')); }
  catch (e) { return { version: 1, reports: [] }; }
}

function fileLabel(name) {
  if (/-full-/i.test(name) || /-full\./i.test(name)) return 'Full deck';
  if (/-preview/i.test(name)) return 'Public preview';
  if (/-appendix/i.test(name)) return 'Appendix';
  return name.replace(/\.pdf$/i, '');
}

function reportIdFromName(name) {
  // e.g. "mu-er-initiation-2026-05-full-r4f7x9k2.pdf" -> "mu-er-initiation-2026-05"
  // Strip trailing -full-*, -preview*, -appendix* and the .pdf extension.
  return name
    .replace(/\.pdf$/i, '')
    .replace(/-(full|preview|appendix)(-[a-z0-9]+)?$/i, '');
}

function main() {
  const existing = loadExisting();
  const byId = new Map();
  for (const r of (existing.reports || [])) byId.set(r.id, r);

  const pdfs = fs.readdirSync(REPORTS_DIR)
    .filter(f => f.toLowerCase().endsWith('.pdf'))
    .sort();

  const groups = new Map(); // id -> {files:[], srcReport}
  for (const name of pdfs) {
    const id = reportIdFromName(name);
    if (!groups.has(id)) groups.set(id, { id, files: [] });
    const stat = fs.statSync(path.join(REPORTS_DIR, name));
    const existingFile = (byId.get(id)?.files || []).find(f => f.path.endsWith('/' + name));
    groups.get(id).files.push({
      label: existingFile?.label || fileLabel(name),
      path: 'assets/reports/' + name,
      size: stat.size,
      gated: existingFile ? existingFile.gated : /-full-/.test(name)
    });
  }

  const reports = Array.from(groups.values()).map(g => {
    const prev = byId.get(g.id) || {};
    return {
      id: g.id,
      title: prev.title || g.id,
      subtitle: prev.subtitle || '',
      type: prev.type || 'report',
      published: prev.published || new Date().toISOString().slice(0, 10),
      page: prev.page || '',
      files: g.files
    };
  }).sort((a, b) => (b.published || '').localeCompare(a.published || ''));

  const out = {
    _comment: 'Auto-generated by tools/build-reports-manifest.js. Edit titles/published/page/notes here; sizes auto-update.',
    version: 1,
    generated: new Date().toISOString(),
    reports
  };

  fs.writeFileSync(MANIFEST, JSON.stringify(out, null, 2) + '\n');
  console.log(`Wrote ${MANIFEST} (${out.reports.length} report(s), ${pdfs.length} file(s))`);
}

main();
